import fs from 'node:fs';
import path from 'node:path';
import { DATA_DIR } from './data.mjs';
import { PUBLIC_DIR } from './renders.mjs';
import { HARNESS_DIR } from './renderEngine.mjs';

const HEADER = '// Generated by `mui verify --all --emit`. Do not edit: re-run the command.\n';
const short = (c) => c.replace(/^Mui/, '');
const RESOLVE_EXT = ['.tsx', '.ts', '.jsx', '.js', '/index.tsx', '/index.ts'];

/** The props a case renders with, parsed the way the harness parses them (only true/false become booleans). */
function propsOf(propsKey) {
  if (!propsKey || propsKey === 'base') {
    return {};
  }
  return Object.fromEntries(propsKey.split(',').map((pair) => {
    const [k, v] = pair.split('=');
    return [k, v === 'true' ? true : v === 'false' ? false : v];
  }));
}

/**
 * Components that are parts of each other share a page: a component joins the group of a shorter name it starts with when
 * both sit on the same MUI docs page, or the name continues at a word boundary and its page names the root (or it has none), unless
 * the root is built on it (ButtonBase under Button is a base, not a part). The group is named after its docs page when a member matches it (Tab + Tabs + TabScrollButton → Tabs).
 */
export function groupComponents(components) {
  const pages = JSON.parse(fs.readFileSync(path.join(DATA_DIR, 'material/demos/index.json'), 'utf8')).demoPages ?? {};
  const { graph } = JSON.parse(fs.readFileSync(path.join(DATA_DIR, 'material/graph.json'), 'utf8'));
  const pageOf = (n) => pages[`Mui${n}`] ?? null;
  const namesPage = (name, page) => [page, page.replace(/e?s$/, '')].includes(name.toLowerCase().replace(/-/g, ''));
  const groups = new Map();
  for (const n of components.map(short).sort((a, b) => a.length - b.length || a.localeCompare(b))) {
    const root = [...groups.keys()].find((r) => {
      const members = groups.get(r);
      const pageFits = !pageOf(n) || (pageOf(r) ? pageOf(n) === pageOf(r) : namesPage(r, pageOf(n)));
      const samePage = Boolean(pageOf(n)) && pageOf(n) === pageOf(r);
      return n.startsWith(r) && (samePage || (/^[A-Z]/.test(n.slice(r.length)) && pageFits)) && !members.some((m) => graph[`Mui${m}`]?.extends === `Mui${n}`);
    });
    if (root) {
      groups.get(root).push(n);
    } else {
      groups.set(n, [n]);
    }
  }
  const named = new Map();
  for (const [root, members] of groups) {
    const page = members.map(pageOf).find(Boolean)?.replace(/-/g, '');
    const name = (page && (members.find((m) => m.toLowerCase() === page) ?? members.find((m) => namesPage(m, page)))) || root;
    named.set(name, members.sort((a, b) => (a === name ? -1 : b === name ? 1 : a.localeCompare(b))));
  }
  return new Map([...named].sort(([a], [b]) => a.localeCompare(b)));
}

/** The docs' static files the emitted demos reference (`/static/images/avatar/1.jpg`), copied from the CLI's data into `assetsDir` at the same path; a path built at runtime brings its folder. Only adds or updates. */
function copyAssets(files, assetsDir) {
  const refs = new Set();
  for (const file of files) {
    for (const [, ref] of fs.readFileSync(file, 'utf8').matchAll(/['"`(](\/static\/[^'"`)\s]+)/g)) {
      refs.add(ref.includes('${') ? `${path.posix.dirname(`${ref.slice(0, ref.indexOf('${'))}x`)}/` : ref);
    }
  }
  const copied = [];
  for (const ref of refs) {
    const from = path.join(PUBLIC_DIR, ref);
    if (!fs.existsSync(from)) {
      continue;
    }
    for (const src of fs.statSync(from).isDirectory() ? fs.readdirSync(from).map((f) => path.join(from, f)) : [from]) {
      const to = path.join(assetsDir, path.relative(PUBLIC_DIR, src));
      if (!fs.existsSync(to) || !fs.readFileSync(to).equals(fs.readFileSync(src))) {
        fs.mkdirSync(path.dirname(to), { recursive: true });
        fs.copyFileSync(src, to);
      }
      copied.push(to);
    }
  }
  return [...new Set(copied)];
}

export const caseId = (c) => `${short(c.component)}|${c.kind}|${c.label}`;

/** Sorted keys at every level, so the same results always serialize to the same text. */
function stable(value) {
  if (Array.isArray(value)) {
    return value.map(stable);
  }
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.keys(value).sort().map((k) => [k, stable(value[k])]));
  }
  return value;
}

/** Copy a source file (and the relative files it imports) under `outDir`, keeping its path below `fromRoot`. Returns its path in `outDir`. */
function copySource(file, fromRoot, outDir, done, write) {
  const rel = path.relative(fromRoot, file);
  const target = path.join(outDir, rel);
  if (!done.has(target)) {
    done.add(target);
    const source = fs.readFileSync(file, 'utf8');
    write(target, source);
    for (const [, spec] of source.matchAll(/from\s+['"](\.{1,2}\/[^'"]+)['"]/g)) {
      const dep = ['', ...RESOLVE_EXT].map((ext) => path.resolve(path.dirname(file), spec + ext)).find((f) => fs.existsSync(f) && fs.statSync(f).isFile());
      if (dep) {
        copySource(dep, fromRoot, outDir, done, write);
      }
    }
  }
  return target;
}

const importPath = (from, to) => {
  const rel = path.relative(path.dirname(from), to).replace(/\.(tsx?|jsx?)$/, '');
  return rel.startsWith('.') ? rel : `./${rel}`;
};

/**
 * Write what a page needs to show the gate's cases live: per component a module of its cases (props, state and the component
 * that renders each), the render modules and demo sources they use, and results.json (checks and failures per case id).
 * Case modules depend only on the CLI's data; results.json changes only when an outcome changes.
 */
export function emitSpecs(outDir, { results, errors, code, components, assetsDir = null }) {
  const dir = path.resolve(outDir);
  fs.mkdirSync(path.join(dir, 'cases'), { recursive: true });
  const written = new Set();
  const write = (file, text) => {
    written.add(file);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) {
      fs.writeFileSync(file, text);
    }
  };
  const copied = new Set();
  const all = [...results.filter((r) => !r.covered).map((r) => ({ c: r.case, r })), ...errors.map((e) => ({ c: e.case, e }))];
  const groups = groupComponents(components);
  const groupOf = new Map([...groups].flatMap(([g, members]) => members.map((m) => [m, g])));
  const byGroup = new Map([...groups.keys()].map((g) => [g, []]));
  for (const item of all) {
    for (const g of new Set((item.c.components ?? [item.c.component]).map((m) => groupOf.get(short(m))))) {
      byGroup.get(g)?.push(item);
    }
  }
  for (const [g, items] of byGroup) {
    const order = groups.get(g);
    items.sort((a, b) => order.indexOf(short(a.c.component)) - order.indexOf(short(b.c.component)));
  }

  const caseResults = {};
  const componentSummary = {};
  const groupSummary = {};
  const seenIds = new Map();
  const idOf = new Map();
  for (const [group, items] of byGroup) {
    if (!items.length) {
      continue;
    }
    const file = path.join(dir, 'cases', `${group}.tsx`);
    const imports = new Map();
    const importOf = (target, named) => {
      const key = `${target}|${named}`;
      if (!imports.has(key)) {
        imports.set(key, { name: `C${imports.size}`, line: named ? `import { Render as C${imports.size} } from '${importPath(file, target)}';` : `import C${imports.size} from '${importPath(file, target)}';` });
      }
      return imports.get(key).name;
    };
    const entries = [];
    for (const { c, r, e } of items) {
      let render;
      let note = null;
      if (c.url.startsWith('/_renders/')) {
        const target = path.join(dir, 'renders', path.basename(c.url));
        if (!copied.has(target)) {
          copied.add(target);
          write(target, fs.readFileSync(path.join(HARNESS_DIR, c.url), 'utf8'));
        }
        render = importOf(target, true);
      } else {
        const source = c.url.replace(/^\/@fs/, '');
        const target = copySource(source, path.join(DATA_DIR, 'material'), path.join(dir, 'demos'), copied, write);
        render = importOf(target, false);
        if (/export const type\b/.test(fs.readFileSync(source, 'utf8'))) {
          note = 'the CLI types into it';
        }
      }
      if (c.interaction?.length) {
        note = 'the CLI opens it';
      }
      if (!idOf.has(c)) {
        const base = caseId(c);
        seenIds.set(base, (seenIds.get(base) ?? 0) + 1);
        idOf.set(c, seenIds.get(base) > 1 ? `${base} #${seenIds.get(base)}` : base);
      }
      const id = idOf.get(c);
      const state = c.kind === 'variant' ? (/ \+(\w+)$/.exec(c.label)?.[1] ?? null) : null;
      const checked = (c.components ?? [c.component]).map(short);
      entries.push(`  { id: ${JSON.stringify(id)}, component: ${JSON.stringify(short(c.component))}, components: ${JSON.stringify(checked)}, kind: ${JSON.stringify(c.kind)}, label: ${JSON.stringify(c.label)}, props: ${JSON.stringify(propsOf(c.propsKey))}, state: ${JSON.stringify(state)}, note: ${JSON.stringify(note)}, Component: ${render} },`);
      caseResults[id] = e
        ? { error: e.error }
        : { checks: r.checks, failures: r.failures.map((f) => ({ rule: f.rule, detail: f.detail })), ...(r.skipped ? { skipped: r.skipped } : {}) };
    }
    write(file, `${HEADER}${[...imports.values()].map((i) => i.line).join('\n')}\n\nexport const cases = [\n${entries.join('\n')}\n];\n`);
    const failedOf = (list) => list.filter(({ r, e }) => e || r.failures.length).length;
    const members = groups.get(group).filter((m) => items.some(({ c }) => (c.components ?? [c.component]).some((x) => short(x) === m)));
    for (const m of members) {
      const mine = items.filter(({ c }) => (c.components ?? [c.component]).some((x) => short(x) === m));
      componentSummary[m] = { cases: mine.length, failed: failedOf(mine), group };
    }
    groupSummary[group] = { components: members, cases: items.length, failed: failedOf(items), ids: items.map(({ c }) => idOf.get(c)) };
  }

  const names = Object.keys(groupSummary).sort();
  write(
    path.join(dir, 'cases', 'index.ts'),
    `${HEADER}export const loaders = {\n${names.map((n) => `  ${JSON.stringify(n)}: () => import('./${n}'),`).join('\n')}\n};\n`,
  );
  const checks = results.reduce((n, r) => n + Object.values(r.checks).reduce((a, b) => a + b, 0), 0);
  const summary = {
    cases: all.length,
    checks,
    failed: all.filter(({ r, e }) => e || r.failures.length).length,
    codeIssues: code.length,
  };
  const out = stable({ summary, groups: groupSummary, components: componentSummary, code: code.map((i) => ({ file: i.file, line: i.line, rule: i.rule, detail: i.detail })), cases: caseResults });
  write(path.join(dir, 'results.json'), `${JSON.stringify(out, null, 2)}\n`);
  const assets = assetsDir ? copyAssets([...written].filter((f) => /\.[jt]sx?$/.test(f)), path.resolve(assetsDir)) : [];
  const walk = (d) => (fs.existsSync(d) ? fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)])) : []);
  for (const stale of ['cases', 'renders', 'demos'].flatMap((sub) => walk(path.join(dir, sub))).filter((f) => !written.has(f))) {
    fs.rmSync(stale);
  }
  return { dir, groups: names.length, components: Object.keys(componentSummary).length, cases: all.length, assets: assets.length };
}
